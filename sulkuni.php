				<div class="grndd" style="margin-bottom: 4em; border: 1px solid #ddd; box-shadow: 0 0 3px 1px #b5acac;">
					<p>
					<p>Our journey in Sulkuni began because of two unique stories of God and His people.</p>

<p>I.&nbsp;<strong>20 Rupees and a heart of love :</strong>&nbsp;When our field workers, Manoranjan Pal, Shaktipad Mondal &amp; Arun Bachaar were returning home on a local train, they met a couple by the name of Sukumar &amp; Karuna Baidya from Sulkuni. They had been robbed (pick pocketed) &amp; were in desperate need for some money in order to return home.</p>

<p>When Manoranjan, Shaktipad &amp; Arun heard of their plight, they gave them 20 rupees. This act of kindness so moved this couple that they began to ask why these men cared for them. This gave them the opportunity of sharing about the love of Jesus. This casual engagement resulted in a regular house meeting being birthed in the home of the Baidya&rsquo;s every week.</p>

<p>When the super cyclone- Aila devastated many parts of Bengal in the year 2006, one of the worst hit areas was Sulkuni. Many were rendered homeless &amp; vulnerable. Around 50 families were forced to take shelter at the local school because they had lost everything during this storm. This was a need that our field workers were able to share with the family of KCF because they were regularly visiting this Island. The family of KCF did the little we could &amp; provided dry food, clean drinking water &amp; roofing materials for them.</p>

<p>II. <strong>A Nurse on a Mission :</strong>&nbsp;A little while later God burdened a young nurse from the UK to partner along with KCF in a quest to take quality &amp; affordable health care to one extremely needy community. When she began to survey the various fields that KCF worked in, the Lord placed an unmistakable burden on her heart for Sulkuni.</p>

<h3>Community Center</h3>

<p>Both of these incredible stories resulted in the establishment of a beautiful Community Center in November, 2015, with a desire to usher holistic transformation to the community in Sulkuni. The following are a few of the highlights of this work as of today:</p>

<ul>
	<li>We have over 3000 registered patients at our medical facility today.</li>
	<li>We have been able to provide free cataract surgeries for many.</li>
	<li>We have conducted numerous health awareness camps.</li>
	<li>We have worked in partnership with the local school to help develop the spoken English skills of the students in this region.</li>
	<li>We have set up the Anugraha &amp; Shanti self-help groups for women.</li>
	<li>We have established a job oriented Sewing Training Program for women in our center.&nbsp;</li>
</ul>
						</p>
